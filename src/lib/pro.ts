/** 12 345 → « 12,3 k » ; garde les chiffres courts sur les cartes */
export function compact(n: number, lang: 'ar' | 'en') {
  return new Intl.NumberFormat(lang === 'ar' ? 'ar-LY-u-nu-latn' : 'en', { notation: 'compact', maximumFractionDigits: 1 }).format(n)
}
