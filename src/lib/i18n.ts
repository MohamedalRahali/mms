export type Strings = (typeof STRINGS)['ar'] & (typeof EXTRA)['ar']

export function makeI18n(lang: Lang) {
  const locale = lang === 'ar' ? 'ar-LY-u-nu-latn' : 'en-GB'
  const dateTime = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'long', hour: '2-digit', minute: '2-digit', timeZone: 'Africa/Tripoli' })
  const timeOnly = new Intl.DateTimeFormat(locale, { hour: '2-digit', minute: '2-digit', timeZone: 'Africa/Tripoli' })
  const dayShort = new Intl.DateTimeFormat(locale, { day: 'numeric', month: 'short', timeZone: 'UTC' })
  const dayLong = new Intl.DateTimeFormat(locale, { weekday: 'long', day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' })
  const capitalize = (s: string) => (s ? s[0].toUpperCase() + s.slice(1) : s)
  return {
    lang,
    dir: (lang === 'ar' ? 'rtl' : 'ltr') as 'rtl' | 'ltr',
    t: { ...STRINGS[lang], ...EXTRA[lang] } as Strings,
    category: (c: string) => CATEGORIES[lang][c] || capitalize(c),
    intl: (k: string) => INTL[lang][k] || k,
    channel: (c: string) => CHANNELS[lang][c] || capitalize(c),
    language: (l: string) => LANGUAGES[lang][l] || l,
    flux: (f: string) => FLUX[lang][f] || f,
    dateTime: (iso: string) => dateTime.format(new Date(iso)),
    time: (iso: string) => timeOnly.format(new Date(iso)),
    day: (isoDay: string) => dayShort.format(new Date(`${isoDay}T12:00:00Z`)),
    dayLong: (isoDay: string) => dayLong.format(new Date(`${isoDay}T12:00:00Z`)),
    num: (n: number) => n.toLocaleString('en-US'),
  }
}

export type I18n = ReturnType<typeof makeI18n>

export const I18nContext = createContext<I18n>(makeI18n('ar'))
export const useI18n = () => useContext(I18nContext)

