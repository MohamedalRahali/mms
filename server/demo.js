export function demoItems() {
  const items = []
  const now = Date.now()
  for (let day = 0; day < 10; day++) {
    if (process.env.MMS_MOSAIQUE === '1')
      MOSAIQUE.forEach(([category, title, summary, broadcasts], i) => {
        if ((i + day) % 3 === 0 && day > 0) return
        items.push({
          id: `demo-m-${day}-${i}`,
          flux: 'mosaique',
          title,
          summary,
          category,
          date: new Date(now - day * 86_400_000 - (i * 53 + 20) * 60_000).toISOString(),
          origin: 'Mosaïque FM',
          channel: 'radio',
          lang: 'ar',
          url: '',
          broadcasts: broadcasts + (day % 2),
          live: false,
          demo: true,
        })
      })
    LIBYE.forEach(([category, title, summary, origin, channel, lang], i) => {
      if ((i + day) % 2 === 0 && day > 0) return
      items.push({
        id: `demo-l-${day}-${i}`,
        flux: 'libye',
        title,
        summary,
        category,
        date: new Date(now - day * 86_400_000 - (i * 71 + 35) * 60_000).toISOString(),
        origin,
        channel,
        lang,
        url: '',
        broadcasts: 1,
        live: false,
        demo: true,
      })
    })
  }
  return items
}
